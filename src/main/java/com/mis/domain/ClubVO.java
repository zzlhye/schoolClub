package com.mis.domain;

import java.util.Date;

public class ClubVO {
	
	private int clubNum;
	private String clubName;
	private String clubInfo;
	private Date regDate;
	private String studentId;
	private String major;
	private String name;
	private String email1;
	private String email2;
	private String phone;
	
	
	public int getClubNum() {
		return clubNum;
	}
	public void setClubNum(int clubNum) {
		this.clubNum = clubNum;
	}
	public String getClubName() {
		return clubName;
	}
	public void setClubName(String clubName) {
		this.clubName = clubName;
	}
	public String getClubInfo() {
		return clubInfo;
	}
	public void setClubInfo(String clubInfo) {
		this.clubInfo = clubInfo;
	}
	public Date getRegDate() {
		return regDate;
	}
	public void setRegDate(Date regDate) {
		this.regDate = regDate;
	}
	public String getStudentId() {
		return studentId;
	}
	public void setStudentId(String studentId) {
		this.studentId = studentId;
	}
	public String getMajor() {
		return major;
	}
	public void setMajor(String major) {
		this.major = major;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public String getEmail1() {
		return email1;
	}
	public void setEmail1(String email1) {
		this.email1 = email1;
	}
	public String getEmail2() {
		return email2;
	}
	public void setEmail2(String email2) {
		this.email2 = email2;
	}
	public String getPhone() {
		return phone;
	}
	public void setPhone(String phone) {
		this.phone = phone;
	}
	@Override
	public String toString() {
		return "ClubVO [clubNum=" + clubNum + ", clubName=" + clubName + ", clubInfo=" + clubInfo + ", regDate="
				+ regDate + ", studentId=" + studentId + ", major=" + major + ", name=" + name + ", email1=" + email1
				+ ", email2=" + email2 + ", phone=" + phone + "]";
	}
	
	
	
}
